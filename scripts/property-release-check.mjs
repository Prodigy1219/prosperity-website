// Actual built-byte checks in two isolated output directories. No deployment.
import assert from 'node:assert/strict';
import { readFileSync, mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { resolve, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';

const root = fileURLToPath(new URL('..', import.meta.url));
const output = mkdtempSync(join(tmpdir(), 'prosperity-property-release-'));
const read = (dir, file) => readFileSync(join(dir, file), 'utf8');

function check(bytes, released) {
  assert.match(bytes.page, /rel="canonical" href="https:\/\/www\.prosperitysmp\.com\/properties"/);
  assert.match(bytes.page, /name="robots" content="noindex, follow"/);
  assert.equal(bytes.home.includes('href="/properties"'), released, 'home footer release gate');
  assert.equal(bytes.page.includes('id="property-desk"'), released, 'page release gate');
  const catalog = JSON.parse(bytes.feed);
  if (released) {
    assert.ok(Array.isArray(catalog.properties) && catalog.properties.length > 0);
    assert.equal(catalog.error, undefined);
  } else {
    assert.equal(catalog.error, 'Property Desk is not released');
    assert.equal(catalog.properties, undefined, 'default build must not contain records');
  }
}

for (const released of [false, true]) {
  const dir = join(output, released ? 'public' : 'held');
  const env = { ...process.env, PROPERTY_DESK_RELEASE: released ? '' : 'held' };
  const proc = spawnSync(process.execPath,
    [resolve(root, 'node_modules/astro/astro.js'), 'build', '--outDir', dir],
    { cwd: root, env, encoding: 'utf8', timeout: 120_000, maxBuffer: 4 * 1024 * 1024 });
  if (proc.status !== 0) throw Error(`Astro build failed: ${proc.status}\n${proc.stdout}\n${proc.stderr}`);
  const bytes = { home: read(dir, 'index.html'), page: read(dir, 'properties/index.html'),
    feed: read(dir, 'property-data/catalog.json') };
  check(bytes, released);
  // Mutate real generated bytes to prove the assertions do not accept a bypass.
  assert.throws(() => check({ ...bytes, home: released
    ? bytes.home.replaceAll('href="/properties"', 'href="/missing-properties"')
    : bytes.home + '<a href="/properties">Properties</a>' }, released));
  assert.throws(() => check({ ...bytes, page: bytes.page.replace('https://www.prosperitysmp.com/properties',
    'https://admin.prosperitysmp.com/properties') }, released));
  if (!released) assert.throws(() => check({ ...bytes,
    feed: JSON.stringify({ error: 'Property Desk is not released', properties: [{}] }) }, false));
  console.log(`PASS ${released ? 'public' : 'held'} build: footer, page, feed, canonical, noindex; mutations rejected`);
}
console.log(`Artifacts retained locally for review: ${output}`);
